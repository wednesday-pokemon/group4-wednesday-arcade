// Copies the canonical pure rules engine (src/game) into the Edge Functions shared folder so the server
// runs byte-identical rules. The copy is GENERATED: edit src/game, then run `npm run sync:shared`.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SOURCE = 'src/game';
const TARGET = 'supabase/functions/_shared/game';
const HEADER = '// GENERATED by scripts/sync-shared.mjs from src/game — do not edit here.\n';

rmSync(TARGET, { recursive: true, force: true });
mkdirSync(TARGET, { recursive: true });
const files = readdirSync(SOURCE).filter((f) => f.endsWith('.ts') && !f.endsWith('.test.ts'));
for (const file of files) {
  writeFileSync(join(TARGET, file), HEADER + readFileSync(join(SOURCE, file), 'utf8'));
}
console.log(`synced ${files.length} rule files -> ${TARGET}`);
