// Copies the canonical pure modules into the Edge Functions shared folder so the server runs byte-identical rules.
// The copies are GENERATED: edit the sources, then run `npm run sync:shared`.
//
//   src/game/*.ts                          -> supabase/functions/_shared/game/          (v2.5 rules engine, whole folder)
//   src/mystery/{types,draft,stats,scoring,caseLogic}.ts (when present)
//   + src/mystery/data/**/*.ts
//   + every src/mystery module those import (transitively, e.g. prf.ts)
//                                          -> supabase/functions/_shared/mystery/       (mystery-v3.1, same layout)
//
// Shared mystery modules must be pure (docs/MYSTERY_CONTRACT.md): they may import only each other and src/game.
// The script FAILS (exit 1) on a bare/out-of-tree import or on Math.random / Date / DOM use, because the Deno
// functions could not run them (or would compute different offers/scores than the browser).
// Identity is enforced by supabase/tests/unit/shared-identity.test.ts.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, posix, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const toPosix = (p) => p.split(sep).join('/');

// ------------------------------------------------------------------------------------------------- v2.5 engine
const GAME_SOURCE = join(ROOT, 'src/game');
const GAME_TARGET = join(ROOT, 'supabase/functions/_shared/game');
export const GAME_HEADER = '// GENERATED by scripts/sync-shared.mjs from src/game — do not edit here.\n';

rmSync(GAME_TARGET, { recursive: true, force: true });
mkdirSync(GAME_TARGET, { recursive: true });
const gameFiles = readdirSync(GAME_SOURCE).filter((f) => f.endsWith('.ts') && !f.endsWith('.test.ts'));
for (const file of gameFiles) {
  writeFileSync(join(GAME_TARGET, file), GAME_HEADER + readFileSync(join(GAME_SOURCE, file), 'utf8'));
}
console.log(`synced ${gameFiles.length} rule files -> supabase/functions/_shared/game`);

// ------------------------------------------------------------------------------------------------- mystery v3.1
const MYSTERY_SOURCE = join(ROOT, 'src/mystery');
const MYSTERY_TARGET = join(ROOT, 'supabase/functions/_shared/mystery');
export const MYSTERY_HEADER = '// GENERATED by scripts/sync-shared.mjs from src/mystery — do not edit here.\n';
// config.ts: DEFAULT_TUNING (derived from data/tuning.ts) holds the egg tier weights + points the run uses, so the
// server can recompute the seed's egg tier exactly like src/mystery/egg.ts createEgg().
const ENTRY_FILES = ['types.ts', 'draft.ts', 'stats.ts', 'scoring.ts', 'caseLogic.ts', 'config.ts'];

function listTs(dir) {
  if (!existsSync(dir)) return [];
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...listTs(full));
    else if (name.endsWith('.ts') && !name.endsWith('.test.ts') && !name.endsWith('.d.ts')) out.push(full);
  }
  return out;
}

/** Relative module specifiers of `import ... from '...'`, `export ... from '...'` and `import('...')`. */
function importSpecifiers(code) {
  const specs = new Set();
  const re = /(?:^|[\s;])(?:import|export)\s[^'"`;]*?from\s*['"]([^'"]+)['"]|(?:^|[\s;])import\s*['"]([^'"]+)['"]|import\(\s*['"]([^'"]+)['"]\s*\)/gm;
  for (const m of code.matchAll(re)) specs.add(m[1] ?? m[2] ?? m[3]);
  return [...specs];
}

/** Code with comments removed (crude but adequate for the purity scan; string contents may be truncated). */
function stripComments(code) {
  return code.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:'"\\])\/\/.*$/gm, '$1');
}

const IMPURE = [
  [/\bMath\.random\s*\(/, 'Math.random()'],
  [/\bDate\.now\s*\(/, 'Date.now()'],
  [/\bnew\s+Date\s*\(/, 'new Date()'],
  [/\bperformance\.now\s*\(/, 'performance.now()'],
  [/\b(?:document|window|localStorage|sessionStorage|navigator)\s*\./, 'DOM / browser globals'],
];

const errors = [];
const included = new Set();
const queue = [];
const skipped = [];
for (const entry of ENTRY_FILES) {
  const full = join(MYSTERY_SOURCE, entry);
  if (existsSync(full)) queue.push(full);
  else skipped.push(entry);
}
queue.push(...listTs(join(MYSTERY_SOURCE, 'data')));

while (queue.length > 0) {
  const file = queue.shift();
  if (included.has(file)) continue;
  included.add(file);
  const rel = toPosix(relative(MYSTERY_SOURCE, file));
  const code = readFileSync(file, 'utf8');
  const bare = stripComments(code);
  for (const [re, label] of IMPURE) if (re.test(bare)) errors.push(`src/mystery/${rel}: uses ${label} (shared modules must be pure)`);
  for (const spec of importSpecifiers(code)) {
    if (!spec.startsWith('.')) {
      errors.push(`src/mystery/${rel}: imports "${spec}" (only relative imports of src/mystery or src/game are allowed)`);
      continue;
    }
    const target = resolve(dirname(file), spec);
    const inMystery = toPosix(relative(MYSTERY_SOURCE, target));
    const inGame = toPosix(relative(GAME_SOURCE, target));
    if (!inGame.startsWith('..') && !posix.isAbsolute(inGame)) {
      if (!gameFiles.includes(inGame)) errors.push(`src/mystery/${rel}: imports src/game/${inGame}, which is not a synced rules file`);
      continue;
    }
    if (inMystery.startsWith('..') || posix.isAbsolute(inMystery)) {
      errors.push(`src/mystery/${rel}: imports "${spec}" outside src/mystery and src/game`);
      continue;
    }
    if (!existsSync(target)) {
      errors.push(`src/mystery/${rel}: imports missing file "${spec}"`);
      continue;
    }
    queue.push(target);
  }
}

if (errors.length > 0) {
  console.error('sync-shared: shared mystery modules violate the purity contract:\n  ' + errors.join('\n  '));
  process.exit(1);
}

rmSync(MYSTERY_TARGET, { recursive: true, force: true });
mkdirSync(MYSTERY_TARGET, { recursive: true });
const copied = [...included].map((f) => toPosix(relative(MYSTERY_SOURCE, f))).sort();
for (const rel of copied) {
  const out = join(MYSTERY_TARGET, rel);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, MYSTERY_HEADER + readFileSync(join(MYSTERY_SOURCE, rel), 'utf8'));
}
console.log(`synced ${copied.length} mystery files -> supabase/functions/_shared/mystery (${copied.join(', ')})`);
if (skipped.length > 0) console.log(`  not present yet (skipped): ${skipped.join(', ')}`);

// ------------------------------------------------------------------------------------------------- registry binding
// supabase/functions/_shared/mystery-registry.generated.ts wires the data registries into the functions. While the
// designer's data files are missing it exports null, and the mystery functions answer 500 MISCONFIGURED instead of
// inventing offers (no placeholder cards can ever be stored).
const REGISTRY_TARGET = join(ROOT, 'supabase/functions/_shared/mystery-registry.generated.ts');
const exportsName = (rel, name) => {
  const full = join(MYSTERY_SOURCE, rel);
  return existsSync(full) && new RegExp(`export\\s+(?:const|let|function)\\s+${name}\\b`).test(readFileSync(full, 'utf8'));
};
const dataReady = exportsName('data/nightshades.ts', 'NIGHTSHADES') && exportsName('data/partners.ts', 'PARTNERS')
  && exportsName('data/case.ts', 'SILENT_EVIDENCE');
const hasDefaultTuning = exportsName('config.ts', 'DEFAULT_TUNING');
const lines = [
  '// GENERATED by scripts/sync-shared.mjs — do not edit. Binds the shared mystery data registries for the Edge Functions.',
  "import type { CaseDef, NightshadeDef, NightshadeId, PokemonId, PokemonPartnerDef } from './mystery/types.ts';",
];
if (hasDefaultTuning) lines.push("import { DEFAULT_TUNING } from './mystery/config.ts';");
if (dataReady) {
  lines.push("import { NIGHTSHADES } from './mystery/data/nightshades.ts';");
  lines.push("import { PARTNERS } from './mystery/data/partners.ts';");
  lines.push("import { SILENT_EVIDENCE } from './mystery/data/case.ts';");
}
lines.push(
  '',
  'export interface MysteryData {',
  '  nightshades: Record<NightshadeId, NightshadeDef>;',
  '  partners: Record<PokemonId, PokemonPartnerDef>;',
  '  caseDef: CaseDef;',
  '}',
  "export interface MysteryEggRules { tierWeights: { common: number; rare: number; legendary: number }; points: { common: number; rare: number; legendary: number } }",
  '',
  dataReady
    ? 'export const MYSTERY_DATA: MysteryData | null = { nightshades: NIGHTSHADES, partners: PARTNERS, caseDef: SILENT_EVIDENCE };'
    : 'export const MYSTERY_DATA: MysteryData | null = null; // src/mystery/data/{nightshades,partners,case}.ts not present yet',
  hasDefaultTuning
    ? 'export const MYSTERY_EGG: MysteryEggRules | null = DEFAULT_TUNING.egg; // the egg rules src/mystery/egg.ts uses'
    : 'export const MYSTERY_EGG: MysteryEggRules | null = null;',
  '',
);
writeFileSync(REGISTRY_TARGET, lines.join('\n'));
console.log(`wrote _shared/mystery-registry.generated.ts (data: ${dataReady ? 'bound' : 'NOT PRESENT'}, egg rules: ${hasDefaultTuning ? 'DEFAULT_TUNING' : 'NOT PRESENT'})`);
