// The Edge Functions must run BYTE-IDENTICAL copies of the pure browser modules (scripts/sync-shared.mjs).
// Fails when someone edits src/game or src/mystery without `npm run sync:shared`, or edits a generated copy by hand.
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

const ROOT = fileURLToPath(new URL('../../..', import.meta.url));
const SHARED = join(ROOT, 'supabase/functions/_shared');
const GAME_HEADER = '// GENERATED by scripts/sync-shared.mjs from src/game — do not edit here.\n';
const MYSTERY_HEADER = '// GENERATED by scripts/sync-shared.mjs from src/mystery — do not edit here.\n';
const MYSTERY_ENTRIES = ['types.ts', 'draft.ts', 'stats.ts', 'scoring.ts', 'caseLogic.ts', 'config.ts'];

function listTs(dir: string): string[] {
  if (!existsSync(dir)) return [];
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...listTs(full));
    else if (name.endsWith('.ts') && !name.endsWith('.test.ts') && !name.endsWith('.d.ts')) out.push(full);
  }
  return out;
}
const rel = (base: string, f: string) => relative(base, f).split(sep).join('/');

describe('shared module copies are identical to their sources', () => {
  it('_shared/game == src/game (both directions)', () => {
    const src = listTs(join(ROOT, 'src/game')).filter((f) => !f.slice(join(ROOT, 'src/game').length + 1).includes(sep));
    const copies = listTs(join(SHARED, 'game'));
    expect(copies.map((f) => rel(join(SHARED, 'game'), f)).sort()).toEqual(src.map((f) => rel(join(ROOT, 'src/game'), f)).sort());
    for (const f of src) {
      const copy = readFileSync(join(SHARED, 'game', rel(join(ROOT, 'src/game'), f)), 'utf8');
      expect(copy, `stale copy of src/game/${rel(join(ROOT, 'src/game'), f)}`).toBe(GAME_HEADER + readFileSync(f, 'utf8'));
    }
  });

  it('every file in _shared/mystery is a header + byte copy of src/mystery', () => {
    const copies = listTs(join(SHARED, 'mystery'));
    expect(copies.length).toBeGreaterThan(0);
    for (const c of copies) {
      const r = rel(join(SHARED, 'mystery'), c);
      const source = join(ROOT, 'src/mystery', r);
      expect(existsSync(source), `orphan copy _shared/mystery/${r}`).toBe(true);
      expect(readFileSync(c, 'utf8'), `stale copy of src/mystery/${r}`).toBe(MYSTERY_HEADER + readFileSync(source, 'utf8'));
    }
  });

  it('every present shared entry module and every data file has a copy', () => {
    const expected = [
      ...MYSTERY_ENTRIES.filter((f) => existsSync(join(ROOT, 'src/mystery', f))),
      ...listTs(join(ROOT, 'src/mystery/data')).map((f) => rel(join(ROOT, 'src/mystery'), f)),
    ];
    for (const r of expected) expect(existsSync(join(SHARED, 'mystery', r)), `missing copy of src/mystery/${r}`).toBe(true);
  });

  it('the generated registry binding matches the data that is present', () => {
    const binding = readFileSync(join(SHARED, 'mystery-registry.generated.ts'), 'utf8');
    const dataPresent = ['nightshades.ts', 'partners.ts', 'cases.ts', 'solutions.ts'].every((f) => existsSync(join(ROOT, 'src/mystery/data', f)));
    expect(dataPresent, 'the three-case data + answer keys are present').toBe(true);
    expect(binding.includes('cases: CASES, solutions: CASE_SOLUTIONS')).toBe(dataPresent);
    expect(binding).toContain("import { CASES } from './mystery/data/cases.ts';");
    expect(binding).toContain("import { CASE_SOLUTIONS } from './mystery/data/solutions.ts';");
    expect(binding, 'the deleted single-case registry must not be bound any more').not.toContain('SILENT_EVIDENCE');
    expect(binding.includes('DEFAULT_TUNING.egg')).toBe(existsSync(join(ROOT, 'src/mystery/config.ts')));
  });

  it('the answer keys are shipped to the functions (server only) together with the public case data', () => {
    expect(existsSync(join(SHARED, 'mystery/data/solutions.ts'))).toBe(true);
    expect(existsSync(join(SHARED, 'mystery/data/cases.ts'))).toBe(true);
    expect(existsSync(join(SHARED, 'mystery/data/case.ts')), 'stale copy of the deleted data/case.ts').toBe(false);
  });
});
